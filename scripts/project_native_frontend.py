"""Project immutable native art and tokens into the existing Python delivery path.

Reads Git blobs from an explicitly supplied local brand checkout; no network,
publisher, model, or runtime operation. The source hashes are admission pins.
The generated Python module is covered by the existing exact source binding,
wheel package, Docker COPY, and canonical software export rules.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "szl-holdings/szl-brand"
BUNDLE = "4309f6fce89179331b0b3ed8c99494e76c5be256"
TOKENS_SOURCE = "27d12e77fc0f9f1a0e5fae8b34adf2380d51d070"
ORBIT_SOURCE = "fd62fe5856ed8e5f660eaae5a9c52957cd71b0a7"
ASSETS = (
    ("TOKEN_CSS", BUNDLE, "kanchay/szl-tokens.css",
     "81f7c9baeef0b435e6e3f9d0c4e0d70e40fa17df5d1f30697f623cd3ef5f8eab"),
    ("SOURCE_MANIFEST", BUNDLE, "kanchay/SOURCE.json",
     "967a77235227f1d75852fb61873e46336e67403cbc0e7e12b141e31c83fbd93d"),
    ("ORBIT_SVG", ORBIT_SOURCE, "kit/logos/orbit-v2/suite/szl-icon-32.svg",
     "6e2b7d72a3af3d9602b79de41df0194ede6496a9661f057108ec224c0efc92e6"),
)


def render(brand_checkout: Path) -> tuple[str, str]:
    constants = []
    installed = []
    for name, commit, path, expected in ASSETS:
        data = subprocess.check_output(
            ["git", "-C", str(brand_checkout), "show", f"{commit}:{path}"],
            stderr=subprocess.PIPE, timeout=15,
        )
        digest = hashlib.sha256(data).hexdigest()
        if digest != expected:
            raise ValueError(f"Native source hash mismatch: {path}")
        constants.append(f"{name} = {data.decode('utf-8')!r}\n")
        installed.append({"constant": name, "source_commit": commit, "source_path": path,
                          "sha256": digest, "bytes": len(data)})
    projection = {
        "schema": "szl.native-python-projection/v1", "unsigned": True,
        "consumer": "szl-holdings/szl-typesafe-triage",
        "source_repository": REPOSITORY, "token_source_commit": TOKENS_SOURCE,
        "assets": installed,
        "delivery": "Exact UTF-8 constants in the source-bound Python package; CSS and Orbit SVG are inlined under the existing nonce CSP.",
        "source_manifest_scope": "Unchanged upstream full manifest, not a claim that all upstream files are installed here.",
        "mark_placement": "Native 32 cut rendered at 40px with 10px clear space; no redraw or filter.",
        "art_attribution": "SZL Holdings / Stephen Lutar, ORCID 0009-0001-0110-4173",
        "art_license": "CC-BY-4.0", "code_license": "Apache-2.0",
    }
    manifest = json.dumps(projection, ensure_ascii=False, indent=2) + "\n"
    module = (
        '# Copyright 2026 SZL Holdings. Code SPDX-License-Identifier: Apache-2.0\n'
        '"""Generated by scripts/project_native_frontend.py; do not edit by hand.\n'
        'Native art: SZL Holdings / Stephen Lutar, CC BY 4.0.\n'
        'Exact upstream source bytes and unsigned projection metadata.\n"""\n\n'
        + "\n".join(constants) + f"\nPROJECTION_JSON = {manifest!r}\n"
    )
    return module, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brand-checkout", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    module, manifest = render(args.brand_checkout)
    outputs = {ROOT / "src/szl_triage/native_assets.py": module,
               ROOT / "docs/native-frontend-projection.json": manifest}
    for path, value in outputs.items():
        if args.check:
            if not path.is_file() or path.is_symlink() or path.read_text(encoding="utf-8") != value:
                raise SystemExit(f"Native projection differs: {path.relative_to(ROOT)}")
        else:
            if path.is_symlink():
                raise SystemExit("Native projection output must not be a symlink")
            path.write_text(value, encoding="utf-8")
    print("Native projection matches immutable sources" if args.check else "Native projection written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
